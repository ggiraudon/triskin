"""Pack the rendered animation frames into the firmware's asset files.

Reads out/frames/<loop>/*.png (written by animate.py) and writes:
  src/assets/character.bin   every frame as raw RGB565, loops in LOOPS order
  src/assets/character.h     frame size, frame rate and frame counts
  src/assets/character.S     embeds character.bin in the firmware

Usage: python tools/character/export.py
"""
import hashlib
from pathlib import Path

import numpy as np
from PIL import Image

from animate import LOOPS

FRAMES = Path(__file__).parent / "out" / "frames"
ASSETS = Path(__file__).parents[2] / "src" / "assets"

# Ordered dithering hides the banding that smooth shading would otherwise show
# with only 5 or 6 bits per channel. The pattern is fixed in screen space, so
# it does not shimmer from frame to frame.
BAYER = (np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) + 0.5) / 16


def to_rgb565(rgb):
    h, w, _ = rgb.shape
    threshold = np.tile(BAYER, (h // 4 + 1, w // 4 + 1))[:h, :w]
    def quantize(channel, levels):
        return np.clip(np.floor(channel / 255 * levels + threshold), 0, levels).astype(np.uint16)
    r, g, b = (rgb[..., i].astype(np.float32) for i in range(3))
    return (quantize(r, 31) << 11) | (quantize(g, 63) << 5) | quantize(b, 31)


def main():
    ASSETS.mkdir(parents=True, exist_ok=True)
    blob = bytearray()
    counts = {}
    size = None
    for name, (_, count, _) in LOOPS.items():
        files = sorted((FRAMES / name).glob("*.png"))
        if len(files) != count:
            raise SystemExit(f"{name}: expected {count} frames, found {len(files)}; run animate.py")
        for f in files:
            rgb = np.asarray(Image.open(f).convert("RGB"))
            size = size or rgb.shape[:2]
            if rgb.shape[:2] != size:
                raise SystemExit(f"{f}: frame size differs from the others")
            blob += to_rgb565(rgb).astype("<u2").tobytes()
        counts[name] = count

    fps = {fps for _, _, fps in LOOPS.values()}
    if len(fps) != 1:
        raise SystemExit("the firmware plays every loop at one frame rate")

    (ASSETS / "character.bin").write_bytes(blob)
    lines = [
        "// Generated by tools/character/export.py. Do not edit.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define CHARACTER_W {size[1]}",
        f"#define CHARACTER_H {size[0]}",
        f"#define CHARACTER_FPS {fps.pop()}",
    ]
    lines += [f"#define CHARACTER_{name.upper()}_FRAMES {count}" for name, count in counts.items()]
    lines += [
        "",
        "// Raw RGB565 frames, one after another: " + ", then ".join(counts) + ".",
        'extern "C" const uint8_t character_frames[];',
        "",
    ]
    (ASSETS / "character.h").write_text("\n".join(lines))

    # The build only re-assembles this file when its text changes; it does not
    # look inside the .bin it pulls in. Stamping it with the frames' checksum
    # is what makes new frames reach the firmware.
    (ASSETS / "character.S").write_text("\n".join([
        "// Generated by tools/character/export.py. Do not edit.",
        "// Embeds the mascot's animation frames (see character.h) in flash.",
        f"// Frames checksum: {hashlib.sha1(blob).hexdigest()}",
        "// The path is relative to the project root, where PlatformIO runs the assembler.",
        '    .section .rodata.character_frames, "a"',
        "    .balign 4",
        "    .global character_frames",
        "character_frames:",
        '    .incbin "src/assets/character.bin"',
        "",
    ]))
    print(f"wrote {len(blob) / 1e6:.1f} MB: " + ", ".join(f"{n} x{c}" for n, c in counts.items()))


if __name__ == "__main__":
    main()
